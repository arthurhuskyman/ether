// Скин «chalk» (минималистичная грифельная доска): звуки мела и стука, мягкая вибрация; графика — обычные иконки. Регистрируется в Skins (js/skins.js).
(function () {
  // двойной штрих: основной + чуть смещённый и повёрнутый второй проход
  // звуки: шорох и стук мела (noise через фильтры), школьный звонок — две ноты колокольчика
  const scratch = (t, d, v, hp, lp) => ({ w: "noise", t, d, v, hp, lp, q: 1.2 });
  const knock = (t, v) => [{ w: "noise", t, d: 0.03, v: v * 1.6, lp: 1400, hp: 200 }, { f: [190, 120], t, d: 0.05, v, w: "sine" }];
  const bell = (f, t, d, v) => [{ f, t, d, v, w: "sine" }, { f: f * 2.76, t, d: d * 0.4, v: v * 0.3, w: "sine" }, { f: f * 5.4, t, d: d * 0.15, v: v * 0.1, w: "sine" }];
  const sound = {
    in: [scratch(0, 0.12, 0.05, 2400, 6500), ...bell(1568, 0.13, 0.55, 0.12), ...bell(1174.7, 0.36, 0.7, 0.11)],
    out: [scratch(0, 0.16, 0.07, 2000, 7000), scratch(0.07, 0.1, 0.05, 3000, 8000), ...knock(0.17, 0.07)],
    tap: [...knock(0, 0.045)],
    tab: [scratch(0, 0.08, 0.05, 2600, 7500), ...knock(0.08, 0.04)],
    react: [...knock(0, 0.05), ...knock(0.07, 0.05)],
    error: [scratch(0, 0.2, 0.08, 800, 2400), ...knock(0.2, 0.08)],
  };
Skins.register("chalk", { sound, haptic: { tap: [4] } });
})();
